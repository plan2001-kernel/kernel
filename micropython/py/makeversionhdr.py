"""Generate the MicroPython version header from the source version macros."""

import argparse
import datetime
import os
import sys


def get_version_info(source_path):
    values = {}
    with open(os.path.join(source_path, "py", "mpconfig.h"), encoding="utf-8") as source:
        for line in source:
            fields = line.split()
            if len(fields) == 3 and fields[0] == "#define" and fields[1] in {
                "MICROPY_VERSION_MAJOR",
                "MICROPY_VERSION_MINOR",
                "MICROPY_VERSION_MICRO",
                "MICROPY_VERSION_PRERELEASE",
            }:
                values[fields[1]] = int(fields[2])
    required = (
        "MICROPY_VERSION_MAJOR",
        "MICROPY_VERSION_MINOR",
        "MICROPY_VERSION_MICRO",
        "MICROPY_VERSION_PRERELEASE",
    )
    if any(name not in values for name in required):
        return None
    prerelease = "-preview" if values["MICROPY_VERSION_PRERELEASE"] else ""
    return "v%d.%d.%d%s" % (
        values["MICROPY_VERSION_MAJOR"],
        values["MICROPY_VERSION_MINOR"],
        values["MICROPY_VERSION_MICRO"],
        prerelease,
    )


def make_version_header(source_path, filename):
    version_tag = os.environ.get("MICROPY_VERSION_TAG") or get_version_info(source_path)
    if not version_tag:
        print("makeversionhdr.py: Error: no version information available.", file=sys.stderr)
        return 1

    if "SOURCE_DATE_EPOCH" in os.environ:
        build_date = datetime.datetime.fromtimestamp(
            int(os.environ["SOURCE_DATE_EPOCH"]), datetime.timezone.utc
        ).date()
    else:
        build_date = datetime.date.today()

    file_data = (
        "// This file was generated by py/makeversionhdr.py\n"
        '#define MICROPY_VERSION_TAG "%s"\n'
        '#define MICROPY_BUILD_DATE "%s"\n'
    ) % (version_tag, build_date.strftime("%Y-%m-%d"))

    if os.path.isfile(filename):
        with open(filename, "r", encoding="utf-8") as current:
            if current.read() == file_data:
                return 0

    print("GEN %s" % filename)
    with open(filename, "w", encoding="utf-8") as output:
        output.write(file_data)
    return 0


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "-r",
        "--source-path",
        default=os.path.join(os.path.dirname(sys.argv[0]), ".."),
        help="path to MicroPython source files",
    )
    parser.add_argument("dest", nargs=1, help="output file path")
    args = parser.parse_args()
    return make_version_header(args.source_path, args.dest[0])


if __name__ == "__main__":
    sys.exit(main())
