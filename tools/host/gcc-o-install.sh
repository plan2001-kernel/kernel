#!/bin/bash
# Plan2001-O GCC ESP installer (N10.1).
#
# Writes the canonical kernel-only plan9.ini (its final byte MUST be LF), the
# GCC kernel and the Clang/LLD PE32+ EFI loader into the ESP, and leaves GRUB
# with exactly one Plan2001-O menu entry: title "Plan2001-O (<kernel UTC
# build stamp>)", id "plan2001-o", chainloading /EFI/plan2001-gcc/BOOTX64.EFI.
#
# Kernel-only is the default: no obootexec selector and no obootrepl line.
# The kernel then opens the configured GE/O volume read-only and holds a
# stable scheduler idle state without an external executable.  MicroPython is
# available only as an explicit compatibility selector:
#   --obootexec 0x4f45584543000003
# which also writes obootrepl=1.  A generic OID writes obootexec only.
#
# The old Plan2001 GRUB sources (42_plan2001, 43_plan2001_o) are kept on
# disk but made non-executable so later grub-mkconfig runs cannot add their
# entries back.  The old ESP directories are not modified.  Debian's GRUB
# default, Debian's own scripts and the UEFI boot order are not changed.
# The installer never formats or writes p5.
#
#   tools/gcc-o-install.sh --plan    --device /dev/nvme0n1p5 --partuuid UUID
#   sudo -n tools/gcc-o-install.sh --install --device ... --partuuid ...
#   sudo -n tools/gcc-o-install.sh --bootstrap --device ... --partuuid ...
#   tools/gcc-o-install.sh --verify  --device ... --partuuid ...
#
# Optional boot selectors, with the current kernel-only plan9.ini bytes as the
# default:
#   --obootexec OID    add obootexec=OID (decimal or 0x-prefixed 64-bit OID;
#                      the MicroPython OID 0x4f45584543000003 is the explicit
#                      compatibility mode and also sets obootrepl=1)
#   --obootcpu CPU     add obootcpu=CPU (exact logical kernel CPU 0..127, < --ncpu)
#   --obootgraph OID   add obootgraph=OID: trusted persistent ObjectSpace root
#                      graph on the obootvol GE/O volume (requires --obootexec)
#   --ncpu N           write *ncpu=N instead of *ncpu=1 (1..128, kernel MAXMACH)
#   --bootmanifest FILE
#                      install FILE as <ESP>/processes.conf and add
#                      bootmanifest=/processes.conf to plan9.ini.  The loader
#                      requires LF termination and no CR/NUL bytes; the
#                      installer stages and verifies the exact bytes.  This is
#                      integrity of the copied file, not manifest
#                      authentication.  Cannot be combined with --obootexec.
#
# --install requires the GCC ESP directory to exist; --bootstrap may create
# it.  Both ensure the single canonical GRUB entry and back up every ESP file
# they replace so a failure can restore both ESP and GRUB.  --plan and
# --verify are read-only for the ESP and GRUB; their reports live under
# build/gcc/o-install.  Pass the same selector flags (including
# --bootmanifest) to --verify as to the original --install.
set -euo pipefail

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
out=${GCC_O_OUT:-$root/build/gcc/o-install}
stage=$out/staging
kernel=${GCC_O_KERNEL:-$root/build/gcc/9pc64.elf}
loader=${GCC_O_LOADER:-$root/build/gcc/bootx64.efi}
newrel=EFI/plan2001-gcc
newtitle=
newid=plan2001-o
kernel_stamp=
grubcfg=/boot/grub/grub.cfg
newscript=/etc/grub.d/44_plan2001_gcc
grubmkconfig=/usr/sbin/grub-mkconfig
grubscriptcheck=/usr/bin/grub-script-check
marker='Plan2001-O single canonical GRUB entry (generated by tools/gcc-o-install.sh)'

mode=plan
esp=
device=
puuid=
obootexec=
obootcpu=
obootgraph=
bootmanifest=
ncpu=1
while [ $# -gt 0 ]; do
	case "$1" in
	--plan) mode=plan ;;
	--install) mode=install ;;
	--bootstrap) mode=bootstrap ;;
	--verify) mode=verify ;;
	--esp) [ $# -ge 2 ] || { echo "--esp needs a path" >&2; exit 2; }; esp=$2; shift ;;
	--device) [ $# -ge 2 ] || { echo "--device needs a path" >&2; exit 2; }; device=$2; shift ;;
	--partuuid) [ $# -ge 2 ] || { echo "--partuuid needs a value" >&2; exit 2; }; puuid=$2; shift ;;
	--obootexec) [ $# -ge 2 ] || { echo "--obootexec needs an OID" >&2; exit 2; }; obootexec=$2; shift ;;
	--obootcpu) [ $# -ge 2 ] || { echo "--obootcpu needs a CPU" >&2; exit 2; }; obootcpu=$2; shift ;;
	--obootgraph) [ $# -ge 2 ] || { echo "--obootgraph needs an OID" >&2; exit 2; }; obootgraph=$2; shift ;;
	--bootmanifest) [ $# -ge 2 ] || { echo "--bootmanifest needs a file" >&2; exit 2; }; bootmanifest=$2; shift ;;
	--ncpu) [ $# -ge 2 ] || { echo "--ncpu needs a count" >&2; exit 2; }; ncpu=$2; shift ;;
	-h|--help) sed -n '2,/^set -euo pipefail$/p' "$0" | sed '$d'; exit 0 ;;
	*) echo "usage: $0 --plan|--install|--bootstrap|--verify --device DEV --partuuid UUID [--esp PATH] [--obootexec OID] [--obootcpu CPU] [--obootgraph OID] [--bootmanifest FILE] [--ncpu N]" >&2; exit 2 ;;
	esac
	shift
done

rollback_state=0
rollback_done=0
esp_backup=$out/esp-backup
esp_restore_list=$out/esp-restore.txt
rollback_esp() {
	local line dst rest mode backup rel tmp
	[ -f "$esp_restore_list" ] || return 0
	say "ROLLBACK: restoring the pre-install ESP files"
	while IFS= read -r line; do
		[ -n "$line" ] || continue
		dst=${line#restore=}
		dst=${dst%% mode=*}
		rest=${line#* mode=}
		mode=${rest%% backup=*}
		backup=${rest#* backup=}
		if [ "$backup" = yes ]; then
			rel=${dst#"$esp"/}
			tmp=$(dirname "$dst")/.$(basename "$dst").rollback.$$
			rdo cp "$esp_backup/$rel" "$tmp" && rdo chmod "$mode" "$tmp" &&
				rdo mv -f "$tmp" "$dst"
		else
			rdo rm -f "$dst"
		fi
	done <"$esp_restore_list"
	rdo sync
}
rollback_grub_core() {
	[ "$rollback_done" = 1 ] && return 0
	rollback_done=1
	set +e
	rollback_esp
	say "ROLLBACK: restoring the pre-install GRUB files"
	rdo cp "$out/grub.cfg.pre" "$grubcfg"
	rdo chmod "$grubcfg_mode" "$grubcfg"
	for f in "${legacy_scripts[@]:-}"; do
		[ -n "$f" ] || continue
		mode=$(sed -n "s|^legacy_script=$f mode=||p" "$out/legacy-pre.txt" 2>/dev/null | head -1)
		[ -n "$mode" ] && rdo chmod "$mode" "$f"
	done
	if [ "${newscript_present:-no}" = yes ]; then
		rdo cp "$out/44_plan2001_gcc.pre" "$newscript"
		rdo chmod "${newscript_mode:-0755}" "$newscript"
	else
		rdo rm -f "$newscript"
	fi
	rdo sync
	say "ROLLBACK: ESP and GRUB files restored to their pre-install state"
}
die() {
	printf 'gcc-o-install: %s\n' "$*" >&2
	if [ "$rollback_state" = 1 ]; then rollback_grub_core; fi
	exit 1
}
say() { printf 'gcc-o-install: %s\n' "$*"; }
sha() { sha256sum "$1" | awk '{print $1}'; }
rsha() { rdo sha256sum "$1" | awk '{print $1}'; }
rdo() {
	if [ "$EUID" -eq 0 ]; then "$@"; else sudo -n "$@"; fi
}
last_byte() { tail -c 1 "$1" | od -An -tx1 | tr -d ' \n'; }
stamp_magic='PLAN2001-O-KERNEL-BUILD:'
stamp_value=
stamp_for() {
	local f=$1 label=$2 raw count stamp
	raw=$(LC_ALL=C grep -aoE 'PLAN2001-O-KERNEL-BUILD:[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2} UTC' "$f" || true)
	count=$(printf '%s\n' "$raw" | grep -c . || true)
	[ "$count" = 1 ] || die "$label kernel has $count build stamps, expected exactly 1"
	stamp=${raw#"$stamp_magic"}
	case "$stamp" in
	[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]\ [0-9][0-9]:[0-9][0-9]\ UTC) ;;
	*) die "$label kernel build stamp is malformed: '$stamp'" ;;
	esac
	[ "$(date -u -d "$stamp" '+%Y-%m-%d %H:%M UTC' 2>/dev/null || true)" = "$stamp" ] || \
		die "$label kernel build stamp is not a valid UTC calendar time: '$stamp'"
	stamp_value=$stamp
}

# Strict selector validation: a full-string decimal or 0x OID no wider than
# 64 bits, and plain decimal CPU/count fields.  Defaults stay unchanged.
valid_oid() {
	local v=$1 name=${2:---obootexec} h
	case "$v" in
	0[xX]*)
		h=${v#0[xX]}
		[ -n "$h" ] || die "invalid $name OID: '$v'"
		[ "${#h}" -le 16 ] || die "invalid $name OID (over 64 bits): '$v'"
		case "$h" in
		*[!0-9a-fA-F]*) die "invalid $name OID: '$v'" ;;
		esac
		;;
	[0-9]*)
		case "$v" in
		*[!0-9]*) die "invalid $name OID: '$v'" ;;
		esac
		[ "${#v}" -le 20 ] || die "invalid $name OID (over 64 bits): '$v'"
		if [ "${#v}" -eq 20 ] && [ "$v" \> "18446744073709551615" ]; then
			die "invalid $name OID (over 64 bits): '$v'"
		fi
		;;
	*) die "invalid $name OID: '$v'" ;;
	esac
}
valid_dec() {
	local v=$1 name=$2
	case "$v" in
	''|*[!0-9]*) die "invalid $name: '$v'" ;;
	esac
	[ "${#v}" -le 10 ] || die "invalid $name: '$v'"
	val_num=$((10#$v))
}
# Keep the selector preflight consistent with the kernel's MAXMACH
# (kernel/amd64/mem.h): the kernel clamps a larger *ncpu to 128, which would
# turn a valid-looking obootcpu >= 128 into a boot-time panic.
maxmach=128
val_num=0
boot_is_mpy=0
manifest_size=0
manifest_sha=
[ -z "$obootexec" ] || valid_oid "$obootexec" "--obootexec"
[ -z "$obootgraph" ] || valid_oid "$obootgraph" "--obootgraph"
if [ -n "$obootexec" ]; then
	case "$obootexec" in
	0[xX]*)
		case "$obootexec" in
		0[xX]0*) die "invalid --obootexec OID: zero is not a selector" ;;
		esac
		;;
	*)
		case "$obootexec" in
		*[!0]*) ;;
		*) die "invalid --obootexec OID: zero is not a selector" ;;
		esac
		;;
	esac
	case "$obootexec" in
	0[xX]4[fF]45584543000003|5712068756889403395) boot_is_mpy=1 ;;
	esac
fi
if [ -n "$obootgraph" ]; then
	case "$obootgraph" in
	0[xX]*)
		case "$obootgraph" in
		0[xX]0*) die "invalid --obootgraph OID: zero is not a selector" ;;
		esac
		;;
	*)
		case "$obootgraph" in
		*[!0]*) ;;
		*) die "invalid --obootgraph OID: zero is not a selector" ;;
		esac
		;;
	esac
	[ -n "$obootexec" ] || die "--obootgraph requires --obootexec"
fi
check_manifest_file() {
	local f=$1 label=$2 size bad
	[ -f "$f" ] || die "$label boot manifest is not a regular file: $f"
	[ -r "$f" ] || die "$label boot manifest is not readable: $f"
	size=$(stat -c %s "$f")
	[ "$size" -ge 1 ] || die "$label boot manifest is empty"
	[ "$size" -le 16383 ] || die "$label boot manifest is too large: $size bytes (max 16383)"
	[ "$(last_byte "$f")" = 0a ] || die "$label boot manifest must end in LF"
	[ "$(tr -d '\000' <"$f" | wc -c | tr -d ' ')" = "$size" ] || \
		die "$label boot manifest contains NUL"
	[ "$(tr -d '\r' <"$f" | wc -c | tr -d ' ')" = "$size" ] || \
		die "$label boot manifest contains CR"
	[ "$(awk 'NF && $0 !~ /^#/ {print; exit}' "$f")" = version=1 ] || \
		die "$label boot manifest must start with version=1"
	grep -q '^\[process\.' "$f" || die "$label boot manifest has no [process.NAME] entries"
	if [ -n "$puuid" ]; then
		bad=$(sed -n 's/.*source=geo:PARTUUID=\([^:]*\):.*/\1/p' "$f" | grep -vx "$puuid" || true)
		[ -z "$bad" ] || die "$label boot manifest PARTUUID does not match --partuuid: $bad"
	fi
}
if [ -n "$bootmanifest" ]; then
	[ -z "$obootexec" ] || die "--bootmanifest cannot be combined with --obootexec"
	[ -z "$obootgraph" ] || die "--bootmanifest cannot be combined with --obootgraph"
	check_manifest_file "$bootmanifest" intended
	manifest_size=$(stat -c %s "$bootmanifest")
	manifest_sha=$(sha "$bootmanifest")
fi
valid_dec "$ncpu" "--ncpu"
ncpu_num=$val_num
[ "$ncpu_num" -ge 1 ] || die "invalid --ncpu: '$ncpu'"
[ "$ncpu_num" -le "$maxmach" ] || die "invalid --ncpu (maximum $maxmach): '$ncpu'"
if [ -n "$obootcpu" ]; then
	valid_dec "$obootcpu" "--obootcpu"
	obootcpu_num=$val_num
	[ "$obootcpu_num" -lt "$maxmach" ] || die "invalid --obootcpu (0..$((maxmach-1))): '$obootcpu'"
fi
if [ -n "$obootcpu" ] && [ "$obootcpu_num" -ge "$ncpu_num" ]; then
	die "--obootcpu $obootcpu must be below --ncpu $ncpu"
fi

[ -n "$device" ] || die "--device is required"
[ -n "$puuid" ] || die "--partuuid is required"
[ -f "$kernel" ] || die "missing $kernel"
[ -f "$loader" ] || die "missing $loader"
[ "$EUID" -eq 0 ] || sudo -n true 2>/dev/null || die "noninteractive sudo is unavailable"

if [ -z "$esp" ]; then
	for p in /boot/efi /efi; do
		[ "$(findmnt -no FSTYPE --target "$p" 2>/dev/null || true)" = vfat ] && { esp=$p; break; }
	done
fi
[ -n "$esp" ] && [ -d "$esp" ] || die "cannot find a mounted vfat ESP; pass --esp"
[ "$(findmnt -no FSTYPE --target "$esp")" = vfat ] || die "$esp is not vfat"

mkdir -p "$out"
# Keep the local evidence directory writable by the invoking user even when
# the privileged install path runs the script through sudo.  This changes
# only build/gcc/o-install, never the ESP or GRUB.
report_uid=${SUDO_UID:-$(id -u)}
report_gid=${SUDO_GID:-$(id -g)}
chown_reports() { chown -R "$report_uid:$report_gid" "$out" 2>/dev/null || true; }
if [ "$EUID" -eq 0 ]; then
	chown_reports
	trap chown_reports EXIT
elif [ -n "$(find "$out" -maxdepth 2 ! -user "$report_uid" -print -quit 2>/dev/null)" ]; then
	sudo -n chown -R "$report_uid:$report_gid" "$out" 2>/dev/null || true
fi
esp_uuid=$(findmnt -no UUID --target "$esp" | head -1)
esp_source=$(findmnt -no SOURCE --target "$esp" | head -1)
[ -n "$esp_uuid" ] || die "cannot determine ESP FAT UUID"

# Live p5 identity.  Only this named partition is checked; it is never written.
dev=$(readlink -f "$device")
[ -b "$dev" ] || die "$device is not a block device"
base=$(basename "$dev")
sys=/sys/class/block/$base
[ -r "$sys/partition" ] || die "$dev is not a partition"
[ "$(cat "$sys/partition")" = 5 ] || die "$dev is not partition 5"
[ "$(readlink -f "/dev/disk/by-partuuid/$puuid" 2>/dev/null || true)" = "$dev" ] || \
	die "PARTUUID $puuid does not resolve to $dev"
dev_size=$(( $(cat "$sys/size") * 512 ))
[ "$dev_size" = 16018046976 ] || die "unexpected p5 size $dev_size"
if findmnt -n "$dev" >/dev/null 2>&1; then die "$dev is mounted"; fi
[ -z "$(ls -A "$sys/holders" 2>/dev/null || true)" ] || die "$dev has holders"

# Artifact checks.
kernel_sha=$(sha "$kernel")
loader_sha=$(sha "$loader")
kernel_size=$(stat -c %s "$kernel")
loader_size=$(stat -c %s "$loader")
readelf -h "$kernel" >"$out/readelf-kernel-h.txt" 2>&1 || die "readelf failed"
grep -q 'Class:[[:space:]]*ELF64' "$out/readelf-kernel-h.txt" || die "kernel is not ELF64"
grep -q 'Type:[[:space:]]*EXEC' "$out/readelf-kernel-h.txt" || die "kernel is not ET_EXEC"
grep -q 'Machine:[[:space:]]*Advanced Micro Devices X86-64' "$out/readelf-kernel-h.txt" || die "kernel is not x86-64"
if nm "$kernel" 2>/dev/null | grep -qE 'mpelf|mpelf_end'; then
	die "kernel still contains mpelf symbols; rebuild without the embedded MicroPython ELF"
fi
file "$loader" >"$out/file-loader.txt" 2>&1
grep -q 'PE32+ executable for EFI (application)' "$out/file-loader.txt" || die "loader is not PE32+ EFI"
objdump -p "$loader" >"$out/objdump-loader.txt" 2>&1
grep -Eq '^Subsystem[[:space:]]+0000000a' "$out/objdump-loader.txt" || die "loader subsystem is not 0xA"

# The kernel's own build identity: exactly one valid UTC stamp, extracted from
# the intended ELF bytes, never from a clock or a sidecar file.  The GRUB title
# is derived from it only after validation.
stamp_for "$kernel" intended
kernel_stamp=$stamp_value
newtitle="Plan2001-O ($kernel_stamp)"

# The plan9.ini contract: the final byte is LF (0x0a).  Write the complete
# file directly to a regular file; never round-trip it through $(...).
write_ini() {
	local f=$1
	printf 'bootfile=/EFI/plan2001-gcc/9pc64.elf\n' >"$f"
	printf 'oboot=server\n' >>"$f"
	printf 'obootvol=PARTUUID=%s\n' "$puuid" >>"$f"
	[ -z "$obootexec" ] || printf 'obootexec=%s\n' "$obootexec" >>"$f"
	[ -z "$obootcpu" ] || printf 'obootcpu=%s\n' "$obootcpu" >>"$f"
	[ -z "$obootgraph" ] || printf 'obootgraph=%s\n' "$obootgraph" >>"$f"
	[ -z "$bootmanifest" ] || printf 'bootmanifest=/processes.conf\n' >>"$f"
	[ "$boot_is_mpy" = 1 ] && printf 'obootrepl=1\n' >>"$f"
	printf '*ncpu=%s\n' "$ncpu" >>"$f"
}

check_ini() {
	local f=$1 label=$2
	[ -s "$f" ] || die "$label plan9.ini is empty"
	[ "$(last_byte "$f")" = 0a ] || die "$label plan9.ini does not end in LF"
	[ "$(stat -c %s "$f")" = "$ini_size" ] || die "$label plan9.ini size mismatch"
	[ "$(sha "$f")" = "$ini_sha" ] || die "$label plan9.ini hash mismatch"
	grep -qx 'bootfile=/EFI/plan2001-gcc/9pc64.elf' "$f" || die "$label plan9.ini bootfile mismatch"
	grep -qx 'oboot=server' "$f" || die "$label plan9.ini is not oboot=server"
	grep -qx "obootvol=PARTUUID=$puuid" "$f" || die "$label plan9.ini PARTUUID mismatch"
	if [ -n "$obootexec" ]; then
		grep -qxF "obootexec=$obootexec" "$f" || die "$label plan9.ini obootexec mismatch"
	else
		! grep -q '^obootexec=' "$f" || die "$label plan9.ini has an unexpected obootexec"
	fi
	if [ -n "$obootcpu" ]; then
		grep -qxF "obootcpu=$obootcpu" "$f" || die "$label plan9.ini obootcpu mismatch"
	else
		! grep -q '^obootcpu=' "$f" || die "$label plan9.ini has an unexpected obootcpu"
	fi
	if [ -n "$obootgraph" ]; then
		grep -qxF "obootgraph=$obootgraph" "$f" || die "$label plan9.ini obootgraph mismatch"
	else
		! grep -q '^obootgraph=' "$f" || die "$label plan9.ini has an unexpected obootgraph"
	fi
	if [ -n "$bootmanifest" ]; then
		grep -qx 'bootmanifest=/processes.conf' "$f" || die "$label plan9.ini bootmanifest mismatch"
	else
		! grep -q '^bootmanifest=' "$f" || die "$label plan9.ini has an unexpected bootmanifest"
	fi
	if [ "$boot_is_mpy" = 1 ]; then
		grep -qx 'obootrepl=1' "$f" || die "$label plan9.ini obootrepl mismatch"
	else
		! grep -q '^obootrepl=' "$f" || die "$label plan9.ini has an unexpected obootrepl"
	fi
	grep -qxF "*ncpu=$ncpu" "$f" || die "$label plan9.ini *ncpu mismatch"
}

check_manifest() {
	local f=$1 label=$2
	check_manifest_file "$f" "$label"
	[ "$(stat -c %s "$f")" = "$manifest_size" ] || die "$label manifest size mismatch"
	[ "$(sha "$f")" = "$manifest_sha" ] || die "$label manifest hash mismatch"
}

# Stage the exact bytes that will be installed.
mkdir -p "$stage/$newrel"
cp "$kernel" "$stage/$newrel/9pc64.elf"
cp "$loader" "$stage/$newrel/BOOTX64.EFI"
write_ini "$stage/$newrel/plan9.ini"
ini_size=$(stat -c %s "$stage/$newrel/plan9.ini")
ini_sha=$(sha "$stage/$newrel/plan9.ini")
check_ini "$stage/$newrel/plan9.ini" staged
if [ -n "$bootmanifest" ]; then
	cp "$bootmanifest" "$stage/processes.conf"
	check_manifest "$stage/processes.conf" staged
fi

# Read the current GRUB state read-only.
rdo test -r "$grubcfg" || die "cannot read $grubcfg"
rdo cat "$grubcfg" >"$out/grub.cfg.pre"
grubcfg_mode=$(rdo stat -c %a "$grubcfg")
grep -Eq '^[[:space:]]*set default="0"' "$out/grub.cfg.pre" || die "GRUB default is not 0 (Debian)"

# Find every executable Plan2001-owned GRUB source other than the canonical
# 44 script.  Only the two known historical files are deactivated; an
# unknown Plan2001 source is a hard stop rather than a guess.
legacy_scripts=()
while IFS= read -r f; do
	[ -f "$f" ] || continue
	[ "$f" = "$newscript" ] && continue
	if grep -qiE 'menuentry.*Plan[[:space:]]*2001|chainloader[[:space:]]+/EFI/plan2001' "$f"; then
		case "$f" in
		/etc/grub.d/42_plan2001|/etc/grub.d/43_plan2001_o)
			legacy_scripts+=("$f") ;;
		*)
			die "unrecognised Plan2001 GRUB source: $f; refusing automatic deactivation" ;;
		esac
	fi
done < <(find /etc/grub.d -maxdepth 1 -type f | sort)

# Stable-id collision check outside our own script.
while IFS= read -r f; do
	[ -f "$f" ] || continue
	[ "$f" = "$newscript" ] && continue
	if grep -Fq -- "--id '$newid'" "$f"; then
		die "GRUB id '$newid' is already used by $f"
	fi
done < <(find /etc/grub.d -maxdepth 1 -type f | sort)

{
	for f in "${legacy_scripts[@]}"; do
		printf 'legacy_script=%s mode=%s\n' "$f" "$(rdo stat -c %a "$f")"
	done
} >"$out/legacy-pre.txt"
if rdo test -e "$newscript"; then
	newscript_present=yes
	rdo cat "$newscript" >"$out/44_plan2001_gcc.pre"
	newscript_mode=$(rdo stat -c %a "$newscript")
else
	newscript_present=no
	newscript_mode=0644
fi
rdo cat "$grubcfg" >"$out/grub.cfg.before"
for f in "${legacy_scripts[@]}"; do
	rdo cat "$f" >"$out/$(basename "$f").pre"
done

plan2001_count_pre=$(awk 'tolower($0) ~ /^[ \t]*(menuentry|submenu)[ \t]/ && tolower($0) ~ /plan[ \t]*2001/ {n++} END{print n+0}' "$out/grub.cfg.pre")
{
	printf 'device=%s\npartuuid=%s\nsize=%s\n' "$dev" "$puuid" "$dev_size"
	printf 'kernel=%s\nkernel_sha256=%s\nkernel_size=%s\n' "$kernel" "$kernel_sha" "$kernel_size"
	printf 'kernel_build_stamp=%s\n' "$kernel_stamp"
	printf 'grub_entry_title=%s\ngrub_entry_id=%s\n' "$newtitle" "$newid"
	printf 'loader=%s\nloader_sha256=%s\nloader_size=%s\n' "$loader" "$loader_sha" "$loader_size"
	printf 'esp=%s\nesp_uuid=%s\nesp_source=%s\n' "$esp" "$esp_uuid" "$esp_source"
	printf 'ini_sha256=%s\nini_size=%s\nini_last_byte=%s\n' "$ini_sha" "$ini_size" "$(last_byte "$stage/$newrel/plan9.ini")"
	printf 'obootexec=%s\nobootcpu=%s\nobootgraph=%s\nncpu=%s\n' "${obootexec:-none}" "${obootcpu:-none}" "${obootgraph:-none}" "$ncpu"
	printf 'bootmanifest=%s\nbootmanifest_esp_path=%s\n' "${bootmanifest:-none}" "$([ -n "$bootmanifest" ] && echo /processes.conf || echo none)"
	printf 'manifest_sha256=%s\nmanifest_size=%s\n' "${manifest_sha:-none}" "${manifest_size:-0}"
	printf 'grub_plan2001_entries_before=%s\nnewscript_present=%s\n' "$plan2001_count_pre" "$newscript_present"
	printf 'date=%s\n' "$(date -Is)"
} >"$out/preflight.txt"

write_grub_script() {
	local f=$1
	{
		printf '#!/bin/sh\n'
		printf '# %s\n' "$marker"
		printf "cat <<'EOT'\n"
		printf "menuentry '%s' --id '%s' {\n" "$newtitle" "$newid"
		printf '\tinsmod part_gpt\n'
		printf '\tinsmod fat\n'
		printf '\tinsmod chain\n'
		printf "\tsearch --no-floppy --fs-uuid --set=root '%s'\n" "$esp_uuid"
		printf '\tchainloader /EFI/plan2001-gcc/BOOTX64.EFI\n'
		printf '}\n'
		printf 'EOT\n'
	} >"$f"
	chmod 0755 "$f"
	sh -n "$f" || die "generated GRUB script does not parse"
}

count_plan2001_entries() {
	awk 'tolower($0) ~ /^[ \t]*(menuentry|submenu)[ \t]/ && tolower($0) ~ /plan[ \t]*2001/ {n++} END{print n+0}' "$1"
}

non_plan2001_entries() {
	awk 'tolower($0) ~ /^[ \t]*(menuentry|submenu)[ \t]/ && tolower($0) !~ /plan[ \t]*2001/ {print}' "$1"
}

check_cfg_contract() {
	local cfg=$1 label=$2 n ids chain oldchain
	n=$(count_plan2001_entries "$cfg")
	[ "$n" = 1 ] || die "$label GRUB config has $n Plan2001 entries, expected exactly 1"
	grep -Fq "menuentry '$newtitle' --id '$newid'" "$cfg" || \
		die "$label GRUB config lacks menuentry '$newtitle' --id '$newid'"
	ids=$(grep -Fc -- "--id '$newid'" "$cfg" || true)
	[ "$ids" = 1 ] || die "$label GRUB config has $ids uses of id '$newid', expected 1"
	chain=$(grep -Fc 'chainloader /EFI/plan2001-gcc/BOOTX64.EFI' "$cfg" || true)
	[ "$chain" = 1 ] || die "$label GRUB config has $chain GCC chainloaders, expected 1"
	oldchain=$(grep -Ec 'chainloader[[:space:]]+/EFI/plan2001(-o)?/' "$cfg" || true)
	[ "$oldchain" = 0 ] || die "$label GRUB config still has $oldchain old Plan2001 chainloader(s)"
	grep -Eq '^[[:space:]]*set default="0"' "$cfg" || die "$label GRUB default is not 0 (Debian)"
	if grep -qiE 'Plan[[:space:]]*2001.*Hardware[[:space:]]+Test' "$cfg"; then
		die "$label GRUB config still names a Plan2001 hardware-test entry"
	fi
}

install_file() {
	local src=$1 dst=$2 tmp
	tmp=$(dirname "$dst")/.$(basename "$dst").tmp.$$
	rdo cp "$src" "$tmp"
	rdo chmod 0644 "$tmp"
	rdo sync
	rdo mv -f "$tmp" "$dst"
	[ "$(rsha "$dst")" = "$(sha "$src")" ] || die "installed $(basename "$dst") hash mismatch"
}

esp_backup_file() {
	local dst=$1 rel
	rel=${dst#"$esp"/}
	if rdo test -e "$dst"; then
		mkdir -p "$esp_backup/$(dirname "$rel")"
		rdo cat "$dst" >"$esp_backup/$rel" || die "cannot back up $dst"
		[ "$(sha "$esp_backup/$rel")" = "$(rsha "$dst")" ] || \
			die "ESP backup hash mismatch for $dst"
		printf 'restore=%s mode=%s backup=yes\n' "$dst" "$(rdo stat -c %a "$dst")" >>"$esp_restore_list"
	else
		printf 'restore=%s mode=- backup=no\n' "$dst" >>"$esp_restore_list"
	fi
}

install_grub_script() {
	local src=$1 tmp
	sh -n "$src" || die "generated GRUB script does not parse"
	tmp=/etc/grub.d/.$(basename "$newscript").tmp.$$
	rdo cp "$src" "$tmp"
	rdo chmod 0755 "$tmp"
	rdo mv -f "$tmp" "$newscript"
}



