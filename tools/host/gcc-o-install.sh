	[ "$stamp_value" = "$kernel_stamp" ] || \
		die "installed kernel build stamp '$stamp_value' does not match intended '$kernel_stamp'"
	[ "$(rsha "$esp/$newrel/BOOTX64.EFI")" = "$loader_sha" ] || die "installed loader hash mismatch"
	rdo cat "$esp/$newrel/plan9.ini" >"$out/plan9.ini.installed"
